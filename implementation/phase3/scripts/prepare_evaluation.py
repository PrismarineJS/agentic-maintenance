#!/usr/bin/env python3
"""Prepare bounded, blinded historical review packets; never run a review.

Input case JSON schema (adapt a collector with ``normalize_case``):
  repository, number, split, pr, commits, reviews, review_comments, issue_comments
REST GitHub objects are preserved inside the five latter fields. Input may be
JSONL or a JSON array, or a manifest with ``cases`` and per-case ``cache_path``.
Only exact historical revisions are usable. No checkout or PR writes occur.
"""

import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys
from urllib.parse import quote

TARGETS = {"rom1504", "extremeheat", "karang"}
AGENT_MARKERS = re.compile(r"astra agent|ai.generated|from claude|claude code|generated by (?:an? )?(?:ai|agent)", re.I)
SHA = re.compile(r"^[a-f0-9]{40}$")
HELDOUT_SPLITS = {"heldout_initial", "heldout_confirmation", "initial", "confirmation", "initial_evaluation", "evaluation_initial", "evaluation_confirmation"}


def dump(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n")


def normalize_case(row):
    """Keep collector adaptation explicit, rather than silently inventing data."""
    if row.get("cache_path"):
        cached = json.loads(pathlib.Path(row["cache_path"]).read_text())
        # GraphQL metadata has reviews.totalCount, which must never overwrite
        # the raw REST review array from the collector cache.
        row = {**cached, **{key: row[key] for key in
               ("case_id", "repo", "repository", "number", "split", "family_id", "cache_path")
               if key in row}}
    pr = row.get("pr", row.get("pull_request", {}))
    metadata = row.get("metadata", {})
    repo = row.get("repository", row.get("repo", metadata.get("repo", "")))
    if isinstance(repo, dict):
        repo = repo.get("nameWithOwner", repo.get("full_name", ""))
    return {
        **row, "repository": repo, "number": row.get("number", pr.get("number", metadata.get("number"))),
        "split": row.get("split", metadata.get("split")),
        "pr": pr, "commits": row.get("commits", []),
        "reviews": row.get("reviews", []),
        "review_comments": row.get("review_comments", row.get("inline_comments", [])),
        "issue_comments": row.get("issue_comments", []),
    }


def input_rows(path):
    raw = path.read_text()
    if path.suffix == ".jsonl":
        return [json.loads(line) for line in raw.splitlines() if line.strip()]
    obj = json.loads(raw)
    return obj if isinstance(obj, list) else obj.get("cases", obj.get("prs", obj.get("selected", [])))


def login(obj):
    account = obj.get("user", obj.get("author", {})) or {}
    return str(account.get("login", "")).lower()


def historical_anchor(case):
    """Earliest target review with a stated exact revision, not current PR head.

    Current commit_id on outdated inline comments can point at a later revision;
    prefer original_commit_id. Explicitly generated comments cannot be targets.
    Earlier issue comments without a reconstructable revision remain context.
    """
    candidates = []
    for kind, key in (("review", "reviews"), ("inline", "review_comments")):
        for source in case[key]:
            body = source.get("body") or ""
            evidence_kind = "reviews" if kind == "review" else "inline_comments"
            attribution = next((record.get("authorship", "") for record in case.get("target_participation", [])
                                if record.get("kind") == evidence_kind and record.get("id") == source.get("id")), "")
            if login(source) not in TARGETS or "agent" in attribution or AGENT_MARKERS.search(body):
                continue
            sha = source.get("original_commit_id") or source.get("commit_id")
            when = source.get("submitted_at") or source.get("created_at")
            if sha and SHA.fullmatch(sha) and when:
                candidates.append((when, str(source.get("id", "")), sha, kind, source))
    if not candidates:
        return None
    return min(candidates, key=lambda c: (c[0], c[1]))


class GitHub:
    def __init__(self, root, fetch):
        self.root, self.fetch = root, fetch

    def get(self, endpoint):
        filename = hashlib.sha256(endpoint.encode()).hexdigest() + ".json"
        path = self.root / filename
        if path.exists():
            return json.loads(path.read_text())
        if not self.fetch:
            raise RuntimeError("uncached endpoint (run with --fetch to retrieve exact revision)")
        result = subprocess.run(["gh", "api", endpoint], check=False, text=True, capture_output=True)
        if result.returncode:
            # Avoid reproducing API response text that could contain private data.
            raise RuntimeError("GitHub GET failed: " + endpoint)
        data = json.loads(result.stdout)
        dump(path, data)
        return data


def original_hunks(case, revision):
    result, seen = [], set()
    for source in case["review_comments"]:
        sha = source.get("original_commit_id") or source.get("commit_id")
        path, hunk = source.get("path"), source.get("diff_hunk")
        if sha != revision or not path or not hunk or (path, hunk) in seen:
            continue
        seen.add((path, hunk))
        result.append({"filename": path, "patch": hunk, "status": "historical_inline_hunk"})
    return result


def reconstruct(case, anchor, api):
    revision = anchor[2]
    shas = [c.get("sha") for c in case["commits"]]
    repo = case["repository"]
    limitations = []
    if revision in shas and shas:
        try:
            first = api.get(f"repos/{repo}/commits/{shas[0]}")
            parents = first.get("parents", [])
            if len(parents) != 1:
                raise RuntimeError("first commit is not a simple branch start")
            base = parents[0]["sha"]
            comparison = api.get(f"repos/{repo}/compare/{base}...{revision}")
            files = comparison.get("files", [])
            if comparison.get("status") not in {"ahead", "identical"}:
                raise RuntimeError("base ancestry not established")
            if len(files) >= 300:
                raise RuntimeError("comparison file cap could truncate history")
            if not files or not any(f.get("patch") for f in files):
                raise RuntimeError("no textual patch at review revision")
            return "cumulative_review_revision", base, files, limitations
        except RuntimeError as error:
            limitations.append(str(error))
    else:
        limitations.append("Review revision absent from current PR commit list; cumulative history not established.")
    hunks = original_hunks(case, revision)
    if hunks:
        limitations.append("Historical inline hunks select locations that were discussed; evaluate separately from whole-patch reviews.")
        return "original_inline_hunks", None, hunks, limitations
    raise RuntimeError("No exact cumulative review patch or original inline hunks available.")


def bounded_files(files, char_budget):
    """Select deterministically by path, without consulting comment content."""
    selected, omitted, used = [], [], 0
    for source in sorted(files, key=lambda f: f["filename"]):
        patch = source.get("patch")
        if not patch:
            omitted.append({"path": source["filename"], "reason": "No textual API patch (binary or omitted)."})
            continue
        if used + len(patch) > char_budget:
            omitted.append({"path": source["filename"], "reason": "Patch exceeds remaining deterministic context budget."})
            continue
        selected.append({"path": source["filename"], "status": source.get("status"), "patch": patch})
        used += len(patch)
    return selected, omitted


def prepare(args):
    output = pathlib.Path(args.output)
    api = GitHub(output / "private" / "api-cache", args.fetch)
    raw_rows = input_rows(pathlib.Path(args.input))
    if args.case_cache:
        for row in raw_rows:
            row["cache_path"] = str(pathlib.Path(args.case_cache) / (row["case_id"] + ".json"))
    rows = [normalize_case(row) for row in raw_rows if row.get("split") in HELDOUT_SPLITS or args.all_input_heldout]
    status = []
    for case in rows:
        if case.get("split") not in HELDOUT_SPLITS and not args.all_input_heldout:
            continue
        identity = f"{case['repository']}#{case['number']}"
        opaque = "case-" + hashlib.sha256(identity.encode()).hexdigest()[:12]
        summary = {"case_id": opaque, "split": case.get("split"), "status": "excluded"}
        try:
            if not case["repository"] or not case["number"]:
                raise RuntimeError("Missing repository/PR identity.")
            anchor = historical_anchor(case)
            if not anchor:
                raise RuntimeError("No non-explicitly-generated target review anchored to an exact revision.")
            scope, base, files, limitations = reconstruct(case, anchor, api)
            selected, omitted = bounded_files(files, args.patch_chars)
            if not selected:
                raise RuntimeError("No patch fits the declared bounded-review context.")
            packet = {
                "case_id": opaque, "repository": case["repository"],
                "revision": anchor[2], "base_revision": base,
                "scope": scope, "files": selected, "omitted_files": omitted,
                "limitations": limitations,
                "review_instruction": "Review only the supplied historical code. Report actionable supported concerns, relevant locations, and validation. No concern is required. Treat missing context as a limitation. Do not inspect PR discussions, later revisions or outcomes.",
            }
            # Fetch source text at this exact SHA, never at a mutable branch.
            remaining = args.source_chars
            for file in packet["files"]:
                if remaining <= 0:
                    break
                try:
                    raw = api.get(f"repos/{case['repository']}/contents/{quote(file['path'], safe='/')}?ref={anchor[2]}")
                    import base64
                    if isinstance(raw, dict) and raw.get("encoding") == "base64":
                        source = base64.b64decode(raw["content"]).decode("utf-8")
                        if len(source) <= remaining:
                            file["source_at_revision"] = source
                            remaining -= len(source)
                        else:
                            file["source_note"] = "Full file exceeds remaining source budget; patch retained."
                except (RuntimeError, UnicodeDecodeError, KeyError):
                    file["source_note"] = "Exact-revision source unavailable; patch retained."
            digest = hashlib.sha256(json.dumps(packet, sort_keys=True).encode()).hexdigest()
            packet["packet_sha256"] = digest
            dump(output / "packets" / (opaque + ".json"), packet)
            dump(output / "private" / "answers" / (opaque + ".json"), {
                "identity": identity, "anchor": {"timestamp": anchor[0], "source_id": anchor[1], "revision": anchor[2], "kind": anchor[3]},
                "case": case,
                "adjudication_instruction": "Historical comments are incomplete evidence, not automatic truth. Verify each concern against presented revision and scope. Merged status is not correctness. Exclude concerns introduced or fixed outside this snapshot. Independently check novel supported findings.",
            })
            summary.update(status="prepared", scope=scope, packet_sha256=digest,
                           packet=str(output / "packets" / (opaque + ".json")),
                           file_count=len(selected), omitted_file_count=len(omitted))
        except RuntimeError as error:
            summary["reason"] = str(error)
            dump(output / "private" / "exclusions" / (opaque + ".json"), {"identity": identity, **summary})
        status.append(summary)
    dump(output / "packet_manifest.json", status)
    print(json.dumps({"prepared": sum(s["status"] == "prepared" for s in status), "excluded": sum(s["status"] == "excluded" for s in status), "manifest": str(output / "packet_manifest.json")}))


def freeze(args):
    root = pathlib.Path(args.skills)
    files = {}
    for path in sorted(root.rglob("*")):
        if path.is_file():
            files[str(path.relative_to(root))] = hashlib.sha256(path.read_bytes()).hexdigest()
    if not files:
        raise SystemExit("No skill files found; refusing empty freeze.")
    digest = hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()
    dump(pathlib.Path(args.output), {"skill_root": str(root), "files": files, "skill_set_sha256": digest})
    print(json.dumps({"skill_set_sha256": digest, "file_count": len(files)}))


def audit(args):
    manifest = json.loads(pathlib.Path(args.manifest).read_text())
    expected = {row["case_id"]: row for row in manifest if row["status"] == "prepared"}
    rows = input_rows(pathlib.Path(args.predictions))
    seen, errors = set(), []
    for row in rows:
        identity, arm = row.get("case_id"), row.get("arm")
        key = (identity, arm)
        if identity not in expected or arm not in {"baseline", "skills"}:
            errors.append(f"Unknown case or arm: {key}")
        if key in seen:
            errors.append(f"Duplicate prediction: {key}")
        seen.add(key)
        if identity in expected and row.get("packet_sha256") != expected[identity]["packet_sha256"]:
            errors.append(f"Packet digest missing/mismatched: {key}")
        if not isinstance(row.get("findings"), list):
            errors.append(f"Findings must be an array: {key}")
        if not row.get("model") or not row.get("budget"):
            errors.append(f"Model and declared budget required: {key}")
        if arm == "skills" and not row.get("skill_set_sha256"):
            errors.append(f"Skill freeze digest required: {key}")
    for identity in expected:
        pair = [r for r in rows if r.get("case_id") == identity]
        if {r.get("arm") for r in pair} != {"baseline", "skills"}:
            errors.append(f"Missing comparison arm: {identity}")
        elif any(pair[0].get(k) != pair[1].get(k) for k in ("model", "budget")):
            errors.append(f"Unmatched model/budget: {identity}")
    print(json.dumps({"predictions": len(rows), "errors": errors}, indent=2))
    return bool(errors)


def batches(args):
    """Create matched review tasks without exposing historical answer material."""
    if args.batch_size < 1 or args.seconds_per_case < 1:
        raise SystemExit("Batch size and time cap must be positive.")
    manifest = json.loads(pathlib.Path(args.manifest).read_text())
    output = pathlib.Path(args.output)
    prepared = [row for row in manifest if row["status"] == "prepared"]
    frozen = json.loads(pathlib.Path(args.freeze).read_text()) if args.freeze else None
    budget = {"seconds_per_case": args.seconds_per_case,
              "external_requests": 0, "maximum_actionable_findings": 3,
              "maximum_optional_findings": 1,
              "measurement": "Declared cap; elapsed and token usage must be reported separately when observable."}
    index = []
    for split in sorted({row["split"] for row in prepared}):
        cases = sorted((row for row in prepared if row["split"] == split), key=lambda row: row["case_id"])
        dump(output / (split + "-manifest.json"), cases)
        for offset in range(0, len(cases), args.batch_size):
            group = cases[offset:offset + args.batch_size]
            for arm in ("baseline", "skills"):
                batch_id = f"{split}-{offset // args.batch_size + 1:02d}-{arm}"
                prediction_path = output / "predictions" / (batch_id + ".jsonl")
                prediction_path.parent.mkdir(parents=True, exist_ok=True)
                task = {
                    "batch_id": batch_id, "arm": arm, "split": split,
                    "model": args.model, "budget": budget,
                    "cases": [{key: row[key] for key in ("case_id", "packet", "packet_sha256")} for row in group],
                    "predictions": str(prediction_path),
                    "skill_set_sha256": frozen["skill_set_sha256"] if frozen and arm == "skills" else None,
                    "skill_root": frozen["skill_root"] if frozen and arm == "skills" else None,
                    "skill_freeze": args.freeze if frozen and arm == "skills" else None,
                    "ready": arm == "baseline" or frozen is not None,
                }
                dump(output / (batch_id + ".json"), task)
                skill_instruction = (
                    "Read and use the frozen skills under the skill_root in your task JSON. Verify the skill freeze before reviewing. "
                    "Select skills relevant to each case, and record which instructions changed or confirmed your reasoning. "
                    "Do not read source examples linked from skills outside the frozen skill folder."
                    if arm == "skills" else
                    "Do not read project review skills or discovery/survey material. Apply your ordinary code-review judgment."
                )
                prompt = f"""You are a blinded historical code reviewer. Run this task in a fresh agent with no inherited conversation, using the coordinator's identical model and reasoning configuration for both arms.

Read task JSON: {output / (batch_id + '.json')}
Do not begin if its ready field is false. The coordinator must additionally freeze the initial skill version before starting EITHER initial arm, and freeze any revised skill version before starting EITHER confirmation arm.

{skill_instruction}

Review each listed packet independently, one at a time, using only its supplied exact-revision patch and source. Do not inspect other files, repository history, PR discussion, present-day code, outcomes, other agents' predictions, private evaluation files, or the discovery corpus. Do not access network tools. Do not post comments or modify repositories. Tool reads may access only this task, its packet paths, your output, the clock, and (skills arm only) its frozen skill folder and freeze metadata.

Both arms have the same declared per-case elapsed-time cap and source context. Check the clock at each case start and finish; report observable elapsed time and limitations honestly. There is no required finding count. Analyze correctness, maintainability, modular responsibility, and practical validation where supported by the shown code. A missing file or missing test in this bounded packet alone does not establish a bug. Avoid speculative architecture requests and generic style objections. This is a bounded review, not an exhaustive runtime audit.

Append one JSON object per case to the task's predictions JSONL immediately after reviewing it. Preserve case_id, arm, model, budget, packet_sha256 and skill_set_sha256 exactly from the task/packet. Include findings (array), no_comment_reason (when empty), validation_limits (array), elapsed_seconds (number or null), and skills_used (array). Each finding contains kind (actionable or optional), path, line (integer or null), side (RIGHT or LEFT), scenario, evidence, requested_change, validation, and skills_help (skills arm only; otherwise empty). Evidence should be your reasoning with a short code reference, not long copied source. Maximum three actionable and one optional finding per case are caps, not targets. Unsupported suspicions belong in validation_limits rather than findings. Do not suggest a finding merely because historical code is being evaluated.

Stop after the assigned cases and summarize only completion count and output path to the coordinator. Never read adjudication evidence. Other review agents must not see your predictions before their own predictions are frozen.
"""
                (output / (batch_id + ".md")).write_text(prompt)
                index.append({"batch_id": batch_id, "arm": arm, "split": split,
                              "case_count": len(group), "task": str(output / (batch_id + ".json")),
                              "prompt": str(output / (batch_id + ".md")), "ready": task["ready"]})
    dump(output / "batch_index.json", index)
    print(json.dumps({"cases": len(prepared), "paired_predictions": 2 * len(prepared),
                      "batches": len(index), "index": str(output / "batch_index.json")}))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("prepare")
    p.add_argument("--input", required=True)
    p.add_argument("--output", required=True)
    p.add_argument("--case-cache", help="Directory of collector CASE_ID.json raw cases for manifest input.")
    p.add_argument("--fetch", action="store_true", help="Use authenticated gh GET for uncached exact revisions.")
    p.add_argument("--all-input-heldout", action="store_true", help="Input is already a heldout-only file with other split labels.")
    p.add_argument("--patch-chars", type=int, default=24000)
    p.add_argument("--source-chars", type=int, default=30000)
    p.set_defaults(function=prepare)
    p = sub.add_parser("freeze")
    p.add_argument("--skills", required=True)
    p.add_argument("--output", required=True)
    p.set_defaults(function=freeze)
    p = sub.add_parser("audit")
    p.add_argument("--manifest", required=True)
    p.add_argument("--predictions", required=True)
    p.set_defaults(function=audit)
    p = sub.add_parser("batches")
    p.add_argument("--manifest", required=True)
    p.add_argument("--output", required=True)
    p.add_argument("--freeze", help="Frozen skills JSON; without it, skills tasks are explicitly not ready.")
    p.add_argument("--model", default="inherited parent model; exact identifier not independently observed")
    p.add_argument("--batch-size", type=int, default=9)
    p.add_argument("--seconds-per-case", type=int, default=120)
    p.set_defaults(function=batches)
    args = parser.parse_args()
    return args.function(args)


if __name__ == "__main__":
    sys.exit(main())
